export const builtInIcons = [...urls.keys()].sort().map((name) => {
  const [category, key] = name.split("/");
  return {
    name,
    label: iconLabels[key] || key,
    category: categoryLabels[category],
  };
});

export function iconURL(name) {
  if (name?.startsWith("custom:"))
    return "/v1/rbac/system/icons/content?name=" + encodeURIComponent(name);
  return (
    urls.get(name) ||
    urls.get(productAliases[name]) ||
    urls.get(legacyIconAliases[name])
  );
}
